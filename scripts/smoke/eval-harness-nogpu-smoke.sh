# No-GPU end-to-end smoke for hipfire-eval.
#
# This exercises the artifact/report/provenance contract with mock rows and a
# generated runtime-evidence JSON file. It is not a quality or performance
# claim; it is a CI-safe harness integrity check.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

OUT_ROOT="${HIPFIRE_EVAL_NOGPU_OUT_ROOT:-$HOME/.hipfire/eval-results/smoke}"
STAMP="${HIPFIRE_EVAL_NOGPU_STAMP:-$(date -u +%Y%m%dT%H%M%SZ)}"
OUT="$OUT_ROOT/nogpu-${STAMP}"
EVIDENCE_JSON="$OUT_ROOT/nogpu-evidence-${STAMP}.json"

pick_eval_bin() {
    if [ -n "${HIPFIRE_EVAL_BIN:-}" ] && [ -x "$HIPFIRE_EVAL_BIN" ]; then
        printf '%s\n' "$HIPFIRE_EVAL_BIN"
        return 0
    fi
    for candidate in \
        "$ROOT/target/debug/hipfire-eval" \
        "$ROOT/target/release/hipfire-eval"; do
        if [ -x "$candidate" ]; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done
    echo "nogpu-smoke: hipfire-eval binary not found; run cargo build -p hipfire-runtime --bin hipfire-eval" >&2
    return 1
}

mkdir -p "$OUT_ROOT"
rm -rf "$OUT"
rm -f "$EVIDENCE_JSON"

python3 - "$EVIDENCE_JSON" <<'PY'
import json
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
path.write_text(
    json.dumps(
        {
            "schema": 1,
            "kind": "launch_counts",
            "records": [
                {
                    "case_id": "nogpu_smoke",
                    "metrics": {
                        "kernel_launches": 3,
                        "graph_launches": 0,
                        "memcpy_ops": 1,
                    },
                    "notes": "generated by eval-harness-nogpu-smoke.sh; ingestion smoke only",
                }
            ],
        },
        indent=2,
    )
    + "\n"
)
PY

EVAL_BIN="$(pick_eval_bin)"
VERSION_REPORT="$("$EVAL_BIN" --version)"
case "$VERSION_REPORT" in
    *"hipfire_version "* ) ;;
    * ) echo "nogpu-smoke: --version missing hipfire_version" >&2; exit 1 ;;
esac
case "$VERSION_REPORT" in
    *"git_commit "* ) ;;
    * ) echo "nogpu-smoke: --version missing git_commit" >&2; exit 1 ;;
esac
"$EVAL_BIN" \
    --model candidate.hfq \
    --baseline baseline.hfq \
    --tier medium \
    --battery barrage,speed \
    --executor mock \
    --offline \
    --evidence-json "$EVIDENCE_JSON" \
    --out "$OUT"

python3 - "$OUT" <<'PY'
import json
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
manifest = json.loads((out / "manifest.json").read_text())
rows = [json.loads(line) for line in (out / "results.jsonl").read_text().splitlines() if line.strip()]
summary = (out / "summary.md").read_text()
admission = json.loads((out / "artifacts" / "admission.json").read_text())
comparison = json.loads((out / "artifacts" / "comparisons.json").read_text())
launch_counts = json.loads((out / "artifacts" / "launch_counts.json").read_text())
barrage_prompts = [
    json.loads(line)
    for line in (out / "artifacts" / "barrage_prompts.jsonl").read_text().splitlines()
    if line.strip()
]

expected_suites = {"gpqa", "lm_eval_micro", "humaneval", "deep_swe", "swe_bench"}
config_suites = set(manifest["config"]["suites"])
if config_suites != expected_suites:
    raise SystemExit(f"nogpu-smoke: unexpected medium suites {sorted(config_suites)}")

if manifest.get("runner") != "hipfire-eval" or not manifest.get("runner_version"):
    raise SystemExit("nogpu-smoke: manifest missing runner/version")
if not manifest.get("hipfire_version") or "git_commit" not in manifest:
    raise SystemExit("nogpu-smoke: manifest missing hipfire version/git fields")
if not manifest.get("binary_hash") or not manifest.get("git_branch"):
    raise SystemExit("nogpu-smoke: manifest missing binary/git provenance")
if not manifest.get("artifacts", {}).get("quality", {}).get("runner_version"):
    raise SystemExit("nogpu-smoke: artifact index missing runner_version")

row_suites = {row.get("suite") for row in rows if row.get("suite")}
if not {"lm_eval_micro", "deep_swe", "swe_bench"}.issubset(row_suites):
    raise SystemExit(f"nogpu-smoke: missing built-in barrage rows {sorted(row_suites)}")
if any(row["status"] == "fail" for row in rows):
    raise SystemExit("nogpu-smoke: result rows contain failures")
if not all(row.get("model_hash") for row in rows):
    raise SystemExit("nogpu-smoke: result rows missing model hashes")
if not any(row.get("prompt_hash") for row in rows):
    raise SystemExit("nogpu-smoke: result rows missing prompt hashes")

ledger_suites = {row.get("suite") for row in barrage_prompts}
if not {"lm_eval_micro", "deep_swe", "swe_bench"}.issubset(ledger_suites):
    raise SystemExit(f"nogpu-smoke: prompt ledger missing built-in suites {sorted(ledger_suites)}")
if not all(row.get("prompt_hash") for row in barrage_prompts):
    raise SystemExit("nogpu-smoke: prompt ledger missing hashes")

if comparison["status"] != "pass" or not comparison["cases"]:
    raise SystemExit("nogpu-smoke: comparison artifact missing comparable cases")
if admission["verdict"] not in {"promote", "reject"}:
    raise SystemExit(f"nogpu-smoke: unexpected admission verdict {admission['verdict']!r}")
if not admission["provenance"].get("runner_version"):
    raise SystemExit("nogpu-smoke: admission missing runner_version")

if launch_counts["status"] != "collected" or not launch_counts["records"]:
    raise SystemExit("nogpu-smoke: launch_counts evidence not collected")
context = launch_counts["records"][0].get("hipfire_eval_context", {})
if context.get("runner") != "hipfire-eval" or not context.get("runner_version"):
    raise SystemExit("nogpu-smoke: external evidence missing runner context")

for required in ["## Models", "## Datasets", "## Admission", "## Evidence Artifacts", "## Rows"]:
    if required not in summary:
        raise SystemExit(f"nogpu-smoke: summary missing {required}")
if "hipfire version:" not in summary or "git commit:" not in summary:
    raise SystemExit("nogpu-smoke: summary missing hipfire version/git provenance")
if "deep_swe" not in summary or "swe_bench" not in summary or "fnv64:" not in summary:
    raise SystemExit("nogpu-smoke: summary missing built-in suite or hash evidence")

print(
    json.dumps(
        {
            "out": str(out),
            "rows": len(rows),
            "ledger_rows": len(barrage_prompts),
            "admission": admission["verdict"],
            "comparison_cases": len(comparison["cases"]),
        },
        sort_keys=True,
    )
)
PY
