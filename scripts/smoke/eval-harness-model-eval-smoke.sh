# Candidate-vs-baseline model-eval smoke for the unified hipfire-eval harness.
#
# This is a validation script, not a quality claim. It combines a tiny generated
# quality fixture plus generated runtime-evidence files with real
# examples-backed speed rows so admission, comparison, manifest, and report
# artifacts are exercised end-to-end on local quantized artifacts.
#
# Environment:
#   HIPFIRE_EVAL_MODEL_SMOKE_CANDIDATE  candidate model path
#   HIPFIRE_EVAL_MODEL_SMOKE_BASELINE   baseline model path
#   HIPFIRE_EVAL_MODEL_SMOKE_OUT_ROOT   output root, default ~/.hipfire/eval-results/smoke
#   HIPFIRE_EVAL_MODEL_SMOKE_MAX_TOKENS decode cap, default 4
#   HIPFIRE_EVAL_MODEL_SMOKE_EXPECT     expected admission verdict, default promote
#   HIPFIRE_EVAL_BIN                    optional hipfire-eval binary override

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

CANDIDATE="${HIPFIRE_EVAL_MODEL_SMOKE_CANDIDATE:-$HOME/.hipfire/models/qwen3.5-0.8b.mq4}"
BASELINE="${HIPFIRE_EVAL_MODEL_SMOKE_BASELINE:-$HOME/.hipfire/models/qwen3.5-0.8b.mq6}"
OUT_ROOT="${HIPFIRE_EVAL_MODEL_SMOKE_OUT_ROOT:-$HOME/.hipfire/eval-results/smoke}"
MAX_TOKENS="${HIPFIRE_EVAL_MODEL_SMOKE_MAX_TOKENS:-4}"
EXPECT="${HIPFIRE_EVAL_MODEL_SMOKE_EXPECT:-promote}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"

if [ ! -f "$CANDIDATE" ]; then
    echo "model-eval-smoke: candidate not found: $CANDIDATE" >&2
    exit 2
fi

if [ ! -f "$BASELINE" ]; then
    echo "model-eval-smoke: baseline not found: $BASELINE" >&2
    exit 2
fi

pick_eval_bin() {
    if [ -n "${HIPFIRE_EVAL_BIN:-}" ] && [ -x "$HIPFIRE_EVAL_BIN" ]; then
        printf '%s\n' "$HIPFIRE_EVAL_BIN"
        return 0
    fi
    for candidate in \
        "$ROOT/target/release/hipfire-eval" \
        "$ROOT/target/debug/hipfire-eval"; do
        if [ -x "$candidate" ]; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done
    echo "model-eval-smoke: hipfire-eval binary not found; run cargo build -p hipfire-runtime --bin hipfire-eval" >&2
    return 1
}

EVAL_BIN="$(pick_eval_bin)"
OUT="$OUT_ROOT/model-eval-${STAMP}"
mkdir -p "$OUT_ROOT"

LOCK_SCRIPT="$ROOT/scripts/gpu-lock.sh"
if [ -r "$LOCK_SCRIPT" ]; then
    # shellcheck disable=SC1090
    . "$LOCK_SCRIPT"
    gpu_acquire "eval-harness-model-eval-smoke"
    trap 'gpu_release 2>/dev/null || true' EXIT
fi

QUALITY_JSON="$OUT_ROOT/model-eval-quality-${STAMP}.json"
EVIDENCE_DIR="$OUT_ROOT/model-eval-evidence-${STAMP}"
mkdir -p "$EVIDENCE_DIR"
python3 - "$QUALITY_JSON" "$EVIDENCE_DIR" <<'PY'
import json
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
evidence_dir = pathlib.Path(sys.argv[2])
rows = [
    {
        "variant": "candidate",
        "arch": "smoke",
        "scoring_mode": "generated_model_eval_smoke_v1",
        "n_chunks": 1,
        "mean_kld": 0.05,
        "mean_kld_ci_lo": 0.04,
        "mean_kld_ci_hi": 0.06,
        "p99_kld": 0.08,
        "ppl": 5.0,
        "notes": "generated by eval-harness-model-eval-smoke.sh; not a quality claim",
    },
    {
        "variant": "baseline",
        "arch": "smoke",
        "scoring_mode": "generated_model_eval_smoke_v1",
        "n_chunks": 1,
        "mean_kld": 0.06,
        "mean_kld_ci_lo": 0.05,
        "mean_kld_ci_hi": 0.07,
        "p99_kld": 0.09,
        "ppl": 5.1,
        "notes": "generated by eval-harness-model-eval-smoke.sh; not a quality claim",
    },
]
path.write_text(json.dumps(rows, indent=2) + "\n")

(evidence_dir / "launch_counts.json").write_text(
    json.dumps(
        {
            "schema": 1,
            "kind": "launch_counts",
            "records": [
                {
                    "case_id": "model_eval_smoke",
                    "metrics": {
                        "kernel_launches": 1,
                        "graph_launches": 0,
                        "memcpy_ops": 0,
                    },
                    "notes": "generated by eval-harness-model-eval-smoke.sh; ingestion smoke only",
                }
            ],
        },
        indent=2,
    )
    + "\n"
)
(evidence_dir / "profiling.json").write_text(
    json.dumps(
        {
            "schema": 1,
            "kind": "profiling",
            "records": [
                {
                    "case_id": "model_eval_smoke",
                    "metrics": {
                        "kernel_name": "smoke_placeholder",
                        "duration_us": 1.0,
                        "occupancy": 0.0,
                        "waves": 0,
                    },
                    "notes": "generated by eval-harness-model-eval-smoke.sh; ingestion smoke only",
                }
            ],
        },
        indent=2,
    )
    + "\n"
)
(evidence_dir / "moe_router_histogram.json").write_text(
    json.dumps(
        {
            "schema": 1,
            "kind": "moe_router_histogram",
            "records": [
                {
                    "case_id": "model_eval_smoke",
                    "metrics": {
                        "expert_hits": {"0": 1},
                        "shared_expert_hits": 0,
                        "router_entropy": 0.0,
                    },
                    "notes": "generated by eval-harness-model-eval-smoke.sh; ingestion smoke only",
                }
            ],
        },
        indent=2,
    )
    + "\n"
)
PY

echo "model-eval-smoke: running candidate=$(basename "$CANDIDATE") baseline=$(basename "$BASELINE")"
"$EVAL_BIN" \
    --model "$CANDIDATE" \
    --baseline "$BASELINE" \
    --battery quality,speed \
    --quality-json "$QUALITY_JSON" \
    --evidence-dir "$EVIDENCE_DIR" \
    --candidate-variant candidate \
    --baseline-variant baseline \
    --executor examples \
    --profile passive \
    --max-tokens "$MAX_TOKENS" \
    --kv-mode q8 \
    --out "$OUT"

python3 - "$OUT" "$EXPECT" <<'PY'
import json
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
expected_verdict = sys.argv[2]
rows = [json.loads(line) for line in (out / "results.jsonl").read_text().splitlines() if line.strip()]
manifest = json.loads((out / "manifest.json").read_text())
comparison = json.loads((out / "artifacts" / "comparisons.json").read_text())
admission = json.loads((out / "artifacts" / "admission.json").read_text())
launch_counts = json.loads((out / "artifacts" / "launch_counts.json").read_text())
profiling = json.loads((out / "artifacts" / "profiling.json").read_text())
moe_router = json.loads((out / "artifacts" / "moe_router_histogram.json").read_text())
summary_md = (out / "summary.md").read_text()

summary = {
    "out": str(out),
    "rows": len(rows),
    "pass": sum(1 for row in rows if row["status"] == "pass"),
    "fail": sum(1 for row in rows if row["status"] == "fail"),
    "skip": sum(1 for row in rows if row["status"] == "skip"),
    "comparison_status": comparison["status"],
    "comparison_cases": len(comparison["cases"]),
    "admission_status": admission["status"],
    "admission_verdict": admission["verdict"],
    "launch_counts_status": launch_counts["status"],
    "profiling_status": profiling["status"],
    "moe_router_status": moe_router["status"],
    "arch": manifest.get("arch"),
    "rocm": manifest.get("rocm"),
    "binary_hash_present": bool(manifest.get("binary_hash")),
}
print(json.dumps(summary, sort_keys=True))

if any(row["status"] == "fail" for row in rows):
    raise SystemExit("model-eval-smoke: result rows contain failures")
if not manifest.get("hipfire_version") or not manifest.get("git_commit"):
    raise SystemExit("model-eval-smoke: manifest missing hipfire version/git provenance")
for required in ["## Models", "## Datasets", "## Admission", "## Evidence Artifacts", "## Rows"]:
    if required not in summary_md:
        raise SystemExit(f"model-eval-smoke: summary missing {required}")
if "hipfire version:" not in summary_md or "git commit:" not in summary_md:
    raise SystemExit("model-eval-smoke: summary missing hipfire version/git provenance")
for required in ["quality", "performance", "launch_counts", "profiling", "moe_router_histogram"]:
    if required not in summary_md:
        raise SystemExit(f"model-eval-smoke: summary missing evidence artifact {required}")
if comparison["status"] != "pass" or not comparison["cases"]:
    raise SystemExit("model-eval-smoke: comparison artifact did not collect comparable cases")
if admission["verdict"] != expected_verdict:
    raise SystemExit(
        f"model-eval-smoke: expected admission verdict {expected_verdict!r}, got {admission['verdict']!r}"
    )
for name, artifact in [
    ("launch_counts", launch_counts),
    ("profiling", profiling),
    ("moe_router_histogram", moe_router),
]:
    if artifact["status"] != "collected" or not artifact["records"]:
        raise SystemExit(f"model-eval-smoke: {name} artifact was not collected")
    context = artifact["records"][0].get("hipfire_eval_context", {})
    if not context.get("model_hash") or not context.get("git_commit"):
        raise SystemExit(f"model-eval-smoke: {name} evidence missing eval context")
PY
