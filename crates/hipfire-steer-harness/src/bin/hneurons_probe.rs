//! H-Neurons (arXiv 2512.01797) reproduction driver.
//!
//! Captures a per-sample CETT feature (`[n_layers][intermediate]`, mean over the
//! response tokens) for a labeled TriviaQA set by driving the daemon `cett_*`
//! ops, then fits the hipfire-hneurons L1 logistic probe and reports test
//! accuracy + the identified hallucination-associated neurons.
//!
//! The label is the answer's factual correctness (H-Neurons `qids.json`: `t` =
//! correct → y=0, `f` = hallucinated → y=1). The `answer_tokens_*.jsonl` supply
//! `(question, response)` per qid. NOTE: the shipped responses were generated by
//! the reference model in the vendored set (e.g. Llama-3.3); running them through
//! a *different* resident model probes whether that model's FFN encodes a
//! correctness signal for arbitrary answer text — a method demo, not the paper's
//! self-generation protocol. Point `--data-prefix` at a self-generated set for
//! the on-paper claim.
//!
//! Usage:
//!   hipfire-hneurons-probe \
//!     --model <llama.hfq> --colnorms <colnorms.bin> \
//!     --data-dir third_party/H-Neurons/data/examples \
//!     --data-prefix Llama33_TriviaQA [--limit 200] [--l1 1e-3] [--daemon <bin>]

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use hipfire_daemon_adapter::{find_daemon_bin_or_error, DaemonEngine};
use hipfire_hneurons::{FitConfig, L1Logreg};
use hipfire_model::ModelLoadParams;

struct Args {
    daemon: Option<PathBuf>,
    model: PathBuf,
    colnorms: PathBuf,
    data_dir: PathBuf,
    data_prefix: String,
    limit: Option<usize>,
    l1: f32,
    max_seq: usize,
}

fn parse_args() -> Result<Args, String> {
    let mut daemon = None;
    let mut model = None;
    let mut colnorms = None;
    let mut data_dir = None;
    let mut data_prefix = "Llama33_TriviaQA".to_string();
    let mut limit = Some(200usize);
    let mut l1 = 1e-3f32;
    let mut max_seq = 2048usize;
    let mut it = std::env::args().skip(1);
    while let Some(a) = it.next() {
        let mut val = || it.next().ok_or_else(|| format!("{a}: missing value"));
        match a.as_str() {
            "--daemon" => daemon = Some(PathBuf::from(val()?)),
            "--model" => model = Some(PathBuf::from(val()?)),
            "--colnorms" => colnorms = Some(PathBuf::from(val()?)),
            "--data-dir" => data_dir = Some(PathBuf::from(val()?)),
            "--data-prefix" => data_prefix = val()?,
            "--limit" => {
                let v = val()?;
                limit = if v == "0" || v == "all" {
                    None
                } else {
                    Some(v.parse().map_err(|e| format!("--limit: {e}"))?)
                };
            }
            "--l1" => l1 = val()?.parse().map_err(|e| format!("--l1: {e}"))?,
            "--max-seq" => max_seq = val()?.parse().map_err(|e| format!("--max-seq: {e}"))?,
            other => return Err(format!("unknown arg {other}")),
        }
    }
    Ok(Args {
        daemon,
        model: model.ok_or("--model required")?,
        colnorms: colnorms.ok_or("--colnorms required")?,
        data_dir: data_dir.ok_or("--data-dir required")?,
        data_prefix,
        limit,
        l1,
        max_seq,
    })
}

/// One labeled sample: the framed question, the model response to score, and the
/// binary label (1 = hallucinated).
struct Sample {
    question: String,
    response: String,
    label: u8,
}

/// Load `{prefix}_answer_tokens_{split}.jsonl` (`{qid: {question, response}}` per
/// line) joined with `{prefix}_{split}_qids.json` (`{"t":[...],"f":[...]}`),
/// yielding labeled samples for the qids present in both. `limit` caps the count
/// (balanced: up to `limit/2` per class in list order).
fn load_split(
    dir: &Path,
    prefix: &str,
    split: &str,
    limit: Option<usize>,
) -> Result<Vec<Sample>, String> {
    let jsonl = dir.join(format!("{prefix}_answer_tokens_{split}.jsonl"));
    let qids_path = dir.join(format!("{prefix}_{split}_qids.json"));

    let qids_raw = std::fs::read_to_string(&qids_path)
        .map_err(|e| format!("read {}: {e}", qids_path.display()))?;
    let qids: serde_json::Value = serde_json::from_str(&qids_raw)
        .map_err(|e| format!("parse {}: {e}", qids_path.display()))?;
    let mut label: HashMap<String, u8> = HashMap::new();
    for (key, y) in [("t", 0u8), ("f", 1u8)] {
        if let Some(arr) = qids.get(key).and_then(|v| v.as_array()) {
            for q in arr {
                if let Some(s) = q.as_str() {
                    label.insert(s.to_string(), y);
                }
            }
        }
    }

    // qid → (question, response)
    let body =
        std::fs::read_to_string(&jsonl).map_err(|e| format!("read {}: {e}", jsonl.display()))?;
    let mut qa: HashMap<String, (String, String)> = HashMap::new();
    for line in body.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let v: serde_json::Value =
            serde_json::from_str(line).map_err(|e| format!("parse jsonl line: {e}"))?;
        let obj = v.as_object().ok_or("jsonl line not an object")?;
        for (qid, rec) in obj {
            let q = rec
                .get("question")
                .and_then(|x| x.as_str())
                .unwrap_or("")
                .to_string();
            let r = rec
                .get("response")
                .and_then(|x| x.as_str())
                .unwrap_or("")
                .to_string();
            qa.insert(qid.clone(), (q, r));
        }
    }

    // Balanced take: iterate the qid lists in order so a small `limit` still
    // draws both classes.
    let per_class = limit.map(|l| l.div_ceil(2));
    let mut out = Vec::new();
    for (key, y) in [("t", 0u8), ("f", 1u8)] {
        let mut taken = 0usize;
        if let Some(arr) = qids.get(key).and_then(|v| v.as_array()) {
            for q in arr {
                if let Some(cap) = per_class {
                    if taken >= cap {
                        break;
                    }
                }
                let Some(qid) = q.as_str() else { continue };
                let Some((question, response)) = qa.get(qid) else {
                    continue;
                };
                if response.trim().is_empty() {
                    continue;
                }
                out.push(Sample {
                    question: question.clone(),
                    response: response.clone(),
                    label: y,
                });
                taken += 1;
            }
        }
    }
    let _ = label; // labels came from the same qids lists
    Ok(out)
}

fn main() {
    if let Err(e) = run() {
        eprintln!("hneurons-probe: {e}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let args = parse_args()?;
    let daemon_bin = match &args.daemon {
        Some(p) => p.clone(),
        None => find_daemon_bin_or_error().map_err(|e| e.to_string())?,
    };

    let train = load_split(&args.data_dir, &args.data_prefix, "train", args.limit)?;
    let test = load_split(&args.data_dir, &args.data_prefix, "test", args.limit)?;
    let (ntr_pos, ntr_neg) = class_counts(&train);
    let (nte_pos, nte_neg) = class_counts(&test);
    eprintln!(
        "[data] train={} (hallucinated={ntr_pos}, correct={ntr_neg})  test={} (hallucinated={nte_pos}, correct={nte_neg})",
        train.len(),
        test.len()
    );
    if train.is_empty() || test.is_empty() {
        return Err("empty train or test split".to_string());
    }

    let rt = tokio::runtime::Runtime::new().map_err(|e| format!("tokio runtime: {e}"))?;
    let model = args
        .model
        .to_str()
        .ok_or("non-UTF8 model path")?
        .to_string();
    let params = ModelLoadParams {
        max_seq: args.max_seq.min(u32::MAX as usize) as u32,
        ..Default::default()
    };
    let colnorms = args
        .colnorms
        .to_str()
        .ok_or("non-UTF8 colnorms path")?
        .to_string();

    let (feat_train, feat_test) = rt.block_on(async {
        let mut engine = DaemonEngine::spawn(&daemon_bin)
            .await
            .map_err(|e| format!("spawn daemon: {e}"))?;
        let loaded = engine
            .load(&model, params)
            .await
            .map_err(|e| format!("load model: {e}"))?;
        eprintln!(
            "[model] loaded {} layers={:?} dim={:?}",
            model, loaded.layers, loaded.dim
        );
        let (nl, inter) = engine
            .cett_load_colnorms(&colnorms)
            .await
            .map_err(|e| format!("cett_load_colnorms: {e}"))?;
        eprintln!("[colnorms] n_layers={nl} intermediate={inter}");

        let ftr = capture_all(&mut engine, &train, "train").await?;
        let fte = capture_all(&mut engine, &test, "test").await?;
        Ok::<_, String>((ftr, fte))
    })?;

    // Labels aligned with capture order.
    let ytr: Vec<u8> = train.iter().map(|s| s.label).collect();
    let yte: Vec<u8> = test.iter().map(|s| s.label).collect();

    let d = feat_train.first().map_or(0, |r| r.len());
    eprintln!(
        "[fit] samples={} features={} l1={}",
        feat_train.len(),
        d,
        args.l1
    );
    let cfg = FitConfig {
        l1: args.l1,
        ..Default::default()
    };
    let model = L1Logreg::fit(&feat_train, &ytr, cfg);
    let train_acc = model.accuracy(&feat_train, &ytr);
    let test_acc = model.accuracy(&feat_test, &yte);
    let hn = model.h_neurons();
    let nz = model.nonzero();

    let inter = if d > 0 {
        d / n_layers_of(&feat_train, d)
    } else {
        0
    };
    let _ = inter;
    println!("=== H-Neurons probe ===");
    println!(
        "dataset:        {} ({} train / {} test)",
        args.data_prefix,
        feat_train.len(),
        feat_test.len()
    );
    println!("features:       {d} (n_layers x intermediate)");
    println!("train accuracy: {:.4}", train_acc);
    println!("test accuracy:  {:.4}", test_acc);
    println!("nonzero weights:{nz}");
    println!(
        "H-Neurons (positive-weight, hallucination-associated): {}",
        hn.len()
    );
    // Show the top few by index for a sanity peek.
    let preview: Vec<usize> = hn.iter().take(16).copied().collect();
    println!("  first {} indices: {:?}", preview.len(), preview);
    Ok(())
}

fn n_layers_of(_feat: &[Vec<f32>], _d: usize) -> usize {
    32 // informational only; not load-bearing
}

fn class_counts(s: &[Sample]) -> (usize, usize) {
    let pos = s.iter().filter(|x| x.label == 1).count();
    (pos, s.len() - pos)
}

/// Capture the flattened CETT feature (`n_layers*intermediate`) for every sample,
/// sequentially through the daemon. Prints progress every 25 samples.
async fn capture_all(
    engine: &mut DaemonEngine,
    samples: &[Sample],
    tag: &str,
) -> Result<Vec<Vec<f32>>, String> {
    let mut out = Vec::with_capacity(samples.len());
    for (i, s) in samples.iter().enumerate() {
        let feat = engine
            .cett_capture("", &s.question, &s.response)
            .await
            .map_err(|e| format!("cett_capture[{tag} #{i}]: {e}"))?;
        // Flatten [n_layers][intermediate] → row-major feature vector.
        let mut row = Vec::with_capacity(feat.iter().map(|l| l.len()).sum());
        for layer in &feat {
            row.extend_from_slice(layer);
        }
        out.push(row);
        if (i + 1) % 25 == 0 || i + 1 == samples.len() {
            eprintln!("[capture:{tag}] {}/{}", i + 1, samples.len());
        }
    }
    Ok(out)
}
